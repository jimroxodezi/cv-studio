import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { promisify } from "node:util";
import { extractText, getDocumentProxy } from "unpdf";

const run = promisify(execFile);
const MAX_CONCURRENCY = Number(process.env.LATEX_MAX_CONCURRENCY || "1");
const COMPILE_TIMEOUT_MS = 60_000;

let active = 0;
const waiting: Array<() => void> = [];

async function withSlot<T>(fn: () => Promise<T>): Promise<T> {
  if (active >= MAX_CONCURRENCY) {
    await new Promise<void>((resolve) => waiting.push(resolve));
  }
  active += 1;
  try {
    return await fn();
  } finally {
    active -= 1;
    waiting.shift()?.();
  }
}

export type CompileResult = {
  pdf: Buffer;
  latex: string;
  pageCount: number;
  atsText: string;
  warnings: string[];
};

function latexDocument(body: string): string {
  return [
    "% Generated by CV Studio. Layout lives in latex/preamble.tex.",
    "\\input{preamble.tex}",
    "\\begin{document}",
    body,
    "\\end{document}",
    "",
  ].join("\n");
}

function pdflatex(cwd: string) {
  return run(
    "pdflatex",
    [
      "-interaction=nonstopmode",
      "-halt-on-error",
      "-file-line-error",
      "-no-shell-escape",
      "main.tex",
    ],
    {
      cwd,
      timeout: COMPILE_TIMEOUT_MS,
      maxBuffer: 10 * 1024 * 1024,
      env: {
        ...process.env,
        openin_any: "p",
        openout_any: "p",
        TEXMFVAR: path.join(cwd, ".texmf-var"),
      },
    },
  );
}

export async function compileCv(body: string): Promise<CompileResult> {
  if (body.length > 80_000) throw new Error("That CV is too long to compile.");
  const latex = latexDocument(body);

  return withSlot(async () => {
    const dir = await mkdtemp(path.join(tmpdir(), "cv-studio-"));
    try {
      const preamble = await readFile(path.join(process.cwd(), "latex", "preamble.tex"), "utf8");
      await writeFile(path.join(dir, "preamble.tex"), preamble, "utf8");
      await writeFile(path.join(dir, "main.tex"), latex, "utf8");

      try {
        // Two passes settle section spacing and hyperref state.
        await pdflatex(dir);
        await pdflatex(dir);
      } catch (err) {
        let log = "";
        try {
          log = await readFile(path.join(dir, "main.log"), "utf8");
        } catch {
          log = err instanceof Error ? err.message : String(err);
        }
        const useful = log
          .split("\n")
          .filter((line) => /^!|^\.\/main\.tex:\d+:|^l\.\d+/.test(line.trim()))
          .slice(0, 8)
          .join("\n");
        throw new Error(`LaTeX could not compile this CV.${useful ? `\n${useful}` : ""}`);
      }

      const pdf = await readFile(path.join(dir, "main.pdf"));
      const warnings = await collectWarnings(dir);

      let pageCount = 1;
      let atsText = "";
      try {
        const doc = await getDocumentProxy(new Uint8Array(pdf));
        const extracted = await extractText(doc, { mergePages: true });
        pageCount = extracted.totalPages || doc.numPages;
        atsText = extracted.text.trim();
      } catch {
        /* keep the PDF even if text extraction fails */
      }

      return { pdf, latex, pageCount, atsText, warnings };
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });
}

async function collectWarnings(dir: string): Promise<string[]> {
  const warnings: string[] = [];
  try {
    const log = await readFile(path.join(dir, "main.log"), "utf8");
    const overfull = log.match(/Overfull \\hbox \(([\d.]+pt) too wide\)/g) ?? [];
    for (const line of overfull.slice(0, 5)) warnings.push(line.replace("Overfull \\hbox ", "Overfull line: "));
    if (log.includes("Missing character:")) warnings.push("Some characters could not be rendered by the font.");
  } catch {
    /* no log */
  }
  return warnings;
}
